#!/usr/bin/env python3
"""
Assemble the Power BI Starter Kit: copy the fictional CSVs into powerbi-kit/files/data,
write powerbi-kit/kit-content.js (so the page can show snippets offline from file://),
and build powerbi-kit/powerbi-starter-kit.zip.
Run after the data generators:  python3 data-generation/build_powerbi_kit.py
"""
import csv, json, os, shutil, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT = os.path.join(ROOT, "powerbi-kit")
FILES = os.path.join(KIT, "files")
DATA = os.path.join(FILES, "data")

def main():
    os.makedirs(DATA, exist_ok=True)
    src = {
        "readiness_monthly.csv": "dashboards/readiness/data/readiness_monthly.csv",
        "events.csv": "dashboards/readiness/data/events.csv",
        "mishaps.csv": "dashboards/safety/data/mishaps.csv",
        "strength.csv": "dashboards/safety/data/strength.csv",
        "status_of_funds.csv": "dashboards/finance/data/status_of_funds.csv",
        "ufr.csv": "dashboards/finance/data/ufr.csv",
    }
    for dst, s in src.items():
        shutil.copyfile(os.path.join(ROOT, s), os.path.join(DATA, dst))
    units = json.load(open(os.path.join(ROOT, "data", "units.json")))["units"]
    with open(os.path.join(DATA, "units.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(units[0].keys())); w.writeheader(); w.writerows(units)
    readme = """POWER BI STARTER KIT - Cole McClintock portfolio
Data shown is fictional for demonstration. Not an official Iowa National Guard product.

Start with docs/build-steps.md (about 30-60 minutes in Power BI Desktop).
A .pbix file is not included; the kit rebuilds it.

theme/   report themes (dark for screen, light for briefings/print)
m/       Power Query (M) scripts: parameter, loader, date table, dims, facts, unpivots, folder load
dax/     measures library (readiness, safety, finance, titles) + one DEFINE file
model/   star-schema.svg (relationships)
docs/    build-steps.md, report-layout.md
data/    fictional CSVs used by the web dashboards
"""
    open(os.path.join(FILES, "README.txt"), "w").write(readme)
    # snippet content for the page
    entries = []
    for group in ("theme", "dax", "m", "docs", "model"):
        d = os.path.join(FILES, group)
        for fn in sorted(os.listdir(d)):
            p = os.path.join(d, fn)
            entries.append(dict(group=group, name=fn, path=f"files/{group}/{fn}", text=open(p, encoding="utf-8").read()))
    with open(os.path.join(KIT, "kit-content.js"), "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by data-generation/build_powerbi_kit.py\nwindow.KIT_FILES = " + json.dumps(entries, ensure_ascii=False) + ";\n")
    zpath = os.path.join(KIT, "powerbi-starter-kit.zip")
    if os.path.exists(zpath): os.remove(zpath)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, fns in os.walk(FILES):
            for fn in sorted(fns):
                full = os.path.join(base, fn)
                z.write(full, os.path.join("portfolio-kit", os.path.relpath(full, FILES)))
    print(len(entries), "snippets;", zpath, os.path.getsize(zpath), "bytes")

if __name__ == "__main__":
    main()
