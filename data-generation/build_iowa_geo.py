#!/usr/bin/env python3
"""Builds dashboards/prevention/data/iowa_geo.js: simplified Iowa state border + county lines as SVG paths and a lookup of
Iowa place coordinates, so the incident map works offline from file://.
Inputs (public domain, U.S. Census Bureau): cartographic boundary files cb_2023_us_state_20m + cb_2023_us_county_20m (shapefiles)
and the 2023 Gazetteer places file for Iowa (2023_gaz_place_19.txt). Pass the folder holding them:  python3 build_iowa_geo.py /tmp/geo
Projection: equirectangular with longitude scaled by cos(42 N), fitted to an SVG viewBox 1000 wide."""
import json, math, os, re, sys
import shapefile  # pyshp

SRC = sys.argv[1] if len(sys.argv) > 1 else "/tmp/geo"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dashboards", "prevention", "data", "iowa_geo.js")
st = [s for s in shapefile.Reader(os.path.join(SRC, "cb_2023_us_state_20m")).iterShapeRecords() if s.record["STATEFP"] == "19"][0]
x0, y0, x1, y1 = st.shape.bbox
K = math.cos(math.radians(42.0)); PAD = 12; W = 1000 - 2 * PAD; S = W / ((x1 - x0) * K)
H = round((y1 - y0) * S + 2 * PAD)
def pr(lon, lat): return (round(PAD + (lon - x0) * K * S, 1), round(PAD + (y1 - lat) * S, 1))
def path(shape):
    out, parts = [], list(shape.parts) + [len(shape.points)]
    for a, b in zip(parts[:-1], parts[1:]):
        pts = [pr(*p) for p in shape.points[a:b]]
        out.append("M" + " ".join("%g,%g" % p for p in pts) + "Z")
    return "".join(out)
counties = [s for s in shapefile.Reader(os.path.join(SRC, "cb_2023_us_county_20m")).iterShapeRecords() if s.record["STATEFP"] == "19"]
def norm(s): return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9]+", " ", s.lower())).strip()
places = {}
with open(os.path.join(SRC, "2023_gaz_place_19.txt"), encoding="utf-8") as f:
    hdr = [h.strip() for h in f.readline().split("\t")]
    for line in f:
        r = dict(zip(hdr, [c.strip() for c in line.split("\t")]))
        name = re.sub(r" (city|CDP|town)$", "", r["NAME"]); k = norm(name)
        if k in places and r["NAME"].endswith("CDP"): continue
        places[k] = [name] + list(pr(float(r["INTPTLONG"]), float(r["INTPTLAT"])))
geo = dict(w=1000, h=H, source="U.S. Census Bureau cartographic boundary files (2023, 1:20,000,000) and 2023 Gazetteer places; simplified",
           state=path(st.shape), counties="".join(path(c.shape) for c in counties), places=places)
with open(OUT, "w") as f:
    f.write("/* Iowa outline, county lines and place coordinates for the offline incident map. Public-domain U.S. Census Bureau data, simplified.\n"
            "   Generated by data-generation/build_iowa_geo.py. */\nwindow.IOWA_GEO = " + json.dumps(geo, separators=(",", ":")) + ";\n")
print(OUT, os.path.getsize(OUT) // 1024, "KB;", len(places), "places;", len(counties), "counties; viewBox 1000 x", H)
