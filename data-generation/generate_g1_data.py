#!/usr/bin/env python3
"""Deterministic, explicitly fictional G1 demos and G1-only templates. No Aviation/finance files are modified."""
from pathlib import Path
import json, datetime as dt, random, shutil
import openpyxl
from openpyxl.styles import Font, PatternFill
from openpyxl.worksheet.table import Table, TableStyleInfo
from openpyxl.utils import get_column_letter
ROOT=Path(__file__).resolve().parents[1]; OUT=ROOT/'dashboards/g1'; DL=ROOT/'downloads'
OUT.mkdir(exist_ok=True);(OUT/'data').mkdir(exist_ok=True)
rng=random.Random(107)
ACCTS=['Funeral Honors','Funeral Honors Stipends','ESGR','Retention','Personnel Ops','Outreach Operations','Outreach Travel','Outreach Supplies']
MONTHS=['October','November','December','January','February','March','April','May','June','July','August','September']
FA=['FAKE-FH','FAKE-FHS','FAKE-ESGR','FAKE-RET','FAKE-OPS','FAKE-OUT-OPS','FAKE-OUT-TRV','FAKE-OUT-SUP']
# PRSA is an MDEP: the three fictional Outreach accounts carry MDEP PRSA (names deliberately do not contain PRSA).
MDEP=['G1XX']*5+['PRSA']*3
H=['fund','contract_doc_no','commitment_item_fipex','functional_area_farea','appropriation_type','fiscal_year','fiscal_month','commitment_amt_cum','disbursement_amt_cum','mdep']
rows=[];fund=[];plan=[]
annual=[360000,180000,450000,720000,540000,240000,120000,90000]
# Fictional PRSA accounts use their own generator so the earlier demo values stay unchanged.
prsa_rng=random.Random(113)
for fy in [2026,2027]:
 for i,acct in enumerate(ACCTS):
  fund.append([fy,acct,annual[i],round(annual[i]*.93,2)])
  for m in range(1,13):
   planned=round(annual[i]/12*(1+.16*(m-6)/6),2);plan.append([fy,acct,m,planned])
   if fy==2027 and m>1:continue
   for j,ci in enumerate(['FAKE-CI1','FAKE-CI2','FAKE-CI3']):
    g=rng if i<5 else prsa_rng
    te=round(planned*[.48,.32,.20][j]*(.85+g.random()*.40),2);disb=round(te*(.60+g.random()*.35),2)
    rows.append(['FAKE-FUND',f'FAKE-DOC-{fy}-{i}-{m}-{j}',ci,FA[i],'OMNG',fy,m,-te,-disb,MDEP[i]])
# Excluded silently as on Aviation
rows.append(['FAKE-FUND','FAKE-SUMMARY','ALLOBJ',FA[0],'OMNG',2027,1,-9999999,-8888888,'G1XX'])
funds={'headers':H,'rows':rows,'funding':{'headers':['Fiscal Year','Account','TDP','AFP'],'rows':fund},'plan':{'headers':['Fiscal Year','Account','Fiscal Month','Planned Amount'],'rows':plan},'key':{'headers':['Functional Area','Account','Sag','MDEP'],'rows':[[fa,a,'FAKE',md] for fa,a,md in zip(FA,ACCTS,MDEP)]},'cikey':{'headers':['Commitment Item','Description'],'rows':[['FAKE-CI1','Pay and allowances'],['FAKE-CI2','Program support'],['FAKE-CI3','Program support']]}}
(OUT/'data/funds_demo.js').write_text('// FICTIONAL G1 demo only. Generated by data-generation/generate_g1_data.py\nwindow.G1_FUNDS_DEMO = '+json.dumps(funds,separators=(',',':'))+';\n')
prh=['Cardholder Name','Purchase requisition','Merchant / Description','Short Text','Total Value']
names=['avery.m.alpha','blake.n.bravo','casey.o.charlie','drew.p.delta','emerson.q.echo']
prs=[]
for level in range(1,5):
 prrows=[]
 for j in range(7):
  pr='FAKE-PR-'+str(level*100+j)
  prrows.extend([[names[j%5],pr,'Fictional Supply Co',f'Office support item {j+1}',125+level*80+j*11],[names[j%5],pr,'Fictional Supply Co',f'Program materials {j+1}',280+level*100+j*17]])
 prs.append({'name':f'L{level}.xlsx','grid':[prh]+prrows})
key=[['Cardholder','Display Name']]+[[n,''] for n in names[:4]]
stip=[['Retiree','Date of service','Cage code','Status']];duty=[['Name','Date performed','UIC','Status']]
for i in range(32):
 d=dt.date(2026,10,1)+dt.timedelta(days=i%28)
 stip.append([['Jordan Alpha','Morgan Bravo','Quinn Charlie','Taylor Delta'][i%4],d.isoformat(),f'FAKE-CAGE-{i%4+1:02d}',['Pending','Submitted','Paid','Awaiting review'][i%4]])
 duty.append([['SGT Avery Alpha','SSG Blake Bravo','SPC Casey Charlie','CPT Drew Delta'][i%4],d.isoformat(),f'FAKE-UIC-{i%3+1:02d}',['Calendar submitted','Not started','PAY SUBMITTED'][i%3]])
dtsh=['Approved date','Last name','First name','TANUM','Departure Date','Location/Destination','Total Obligation ($)','Ignored column']
dts=[[f'Fictional DTS report preamble line {n}'] for n in range(1,10)]+[dtsh]
for i in range(24):
 approved=dt.date(2026,10,1)+dt.timedelta(days=i%28);depart=approved+dt.timedelta(days=8)
 dts.append([approved.isoformat(),['ALPHA',"O'BRAVO",'CHARLIE-DELTA','ECHO'][i%4],['AVERY','BLAKE','CASEY','DREW'][i%4],f'FAKE-TANUM-{i if i!=23 else 1:04d}',depart.isoformat(),['Fictional City A','Fictional City B','Fictional City C','Fictional City D'][i%4],round(450+i*63.71,2),'Not read'])
demo={'pr':prs,'prKey':{'name':'G1 Cardholder Key.xlsx','grid':key},'stip':{'name':'G1 Stipends.xlsx','grid':stip},'duty':{'name':'G1 MFH Duty.xlsx','grid':duty},'dts':{'name':'G1 DTS.xlsx','grid':dts}}
(OUT/'data/g1_demo.js').write_text('// FICTIONAL G1 names, codes and report data only.\nwindow.G1_DEMO = '+json.dumps(demo,separators=(',',':'))+';\n')
def workbook(file,headers,rows=None,tab='G1Template',table='G1Data',note=''):
 wb=openpyxl.Workbook();ws=wb.active;ws.title=tab
 ws.append(headers)
 for row in rows or [[None]*len(headers)]:ws.append(row)
 for c in ws[1]:c.font=Font(bold=True);c.fill=PatternFill('solid',fgColor='DBEAFE')
 t=Table(displayName=table,ref=f'A1:{get_column_letter(len(headers))}{ws.max_row}');t.tableStyleInfo=TableStyleInfo(name='TableStyleMedium2',showRowStripes=True);ws.add_table(t)
 for i in range(1,len(headers)+1):ws.column_dimensions[get_column_letter(i)].width=23
 if note:ws.cell(1,len(headers)+2,'G1 Dashboard');ws.cell(2,len(headers)+2,note);ws.column_dimensions[get_column_letter(len(headers)+2)].width=85
 ws.freeze_panes='A2';wb.save(OUT/file)
 shutil.copyfile(OUT/file,DL/('g1-'+file.removeprefix('g1_').replace('_','-')))
workbook('g1_accountkey_template.xlsx',['Functional Area','Account','Sag','MDEP'],tab='G1AccountKey',table='G1AccountKey',note='G1 Account Key only. Functional Areas map to G1 account names; these do not affect Aviation.')
workbook('g1_cikey_template.xlsx',['Commitment Item','Description'],tab='G1CIKey',table='G1CIKey',note='G1 Commitment Item Key only. Items sharing a description are combined.')
workbook('g1_funding_template.xlsx',['Fiscal Year','Account','TDP','AFP'],tab='G1Funding',table='G1Funding',note='G1 funding file only. Account names must match the G1 Account Key. No Reservations.')
workbook('g1_cardholder_key_template.xlsx',['Cardholder','Display Name'],tab='G1CardholderKey',table='CardholderKey',note='G1 Cardholder Key only. Optional Display Name. No Type split. Match on normalized first and last name.')
workbook('g1_spendplan_template.xlsx',['Account']+MONTHS,tab='G1SpendPlan',table='G1SpendPlan',note='Current fiscal year (1 October starts the next). Account names mirror the G1 Account Key. Dollars as entered.')
workbook('g1_stipends_template.xlsx',['Retiree','Date of service','Cage code','Status'],tab='G1Stipends',table='G1Stipends',note='One row per service. Status is displayed as entered.')
workbook('g1_mfh_duty_template.xlsx',['Name','Date performed','UIC','Status'],tab='G1MFHDuty',table='G1MFHDuty',note='Statuses: Calendar submitted, Not started, Pay submitted (case-insensitive).')
workbook('funds_template.xlsx',H,tab='G1Funds',table='G1Funds',note='G1 SOF export. commitment_amt_cum = Total Expenditure; disbursement_amt_cum = Disbursements (both negative in the export).')
workbook('g1_pay_rates_template.xlsx',['Grade','Daily rate'],rows=[[g,None] for g in ['E1','E2','E3','E4','E5','E6','E7','E8','E9','W1','W2','W3','W4','W5','O1','O2','O3','O4','O5','O6']],tab='Rates',table='G1PayRates',note='G1 PRSA Planner daily pay rates. Enter your own $ per day for each grade; blank by default (no built-in pay table).')
workbook('pr_template.xlsx',prh,tab='G1PRs',table='G1PRs',note='Name the file L1.xlsx, L2.xlsx, L3.xlsx or L4.xlsx.')
wb=openpyxl.Workbook();ws=wb.active;ws.title='G1 DTS Sample'
for row in dts:ws.append(row)
ws.freeze_panes='A11'
for i in range(1,9):ws.column_dimensions[get_column_letter(i)].width=27
wb.save(OUT/'g1_dts_sample.xlsx');shutil.copyfile(OUT/'g1_dts_sample.xlsx',DL/'g1-dts-sample.xlsx')
print('G1 fictional demos and separate templates generated')
